        (wallets && walletPackages.contains(pkg)) ||
        (smsPackages.contains(pkg) &&
            senderAliases.contains(title.trim().toLowerCase()) &&
            (wallets ||
                !{
                  'momo',
                  'zalopay',
                  'viettelmoney',
                  'viettel money',
                  'viettelpay',
                  'vnpay',
                  'shopeepay'
                }.contains(title.trim().toLowerCase())));
